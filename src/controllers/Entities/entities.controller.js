const ROLE_RANK = {
    'Admin': 1,
    'Branch': 2,
    'Employee': 3,
    'Partner': 4,
    'User': 5
};

/**
 * @desc    Create a new user or entity according to hierarchy
 * @route   POST /api/entities/register
 * @access  Private / Public (First Admin)
 */
export const createUser = asyncHandler(async (req, res) => {
    const { fullName, email, mobile, role } = req.body;

    const creator = req.user;
    const creatorId = creator ? creator.id : null;

    // Default role to 'Admin' if not provided in req.body
    const userRole = role || 'Admin';

    // If no user is logged in (no token passed)
    if (!creator) {
        const adminCount = await User.count({ where: { role: 'Admin' } });
        if (adminCount > 0) {
            throw new ApiError(HTTP_STATUS.UNAUTHORIZED, "Access Denied. Token is required to create users.");
        }
        if (userRole !== 'Admin') {
            throw new ApiError(HTTP_STATUS.BAD_REQUEST, "Initial user created in system must be an Admin.");
        }
    } else {
        // User is logged in: Enforce strict hierarchy
        const creatorRank = ROLE_RANK[creator.role];
        const targetRank = ROLE_RANK[userRole];

        if (!targetRank) {
            throw new ApiError(HTTP_STATUS.BAD_REQUEST, "Invalid role specified.");
        }

        // Creator can ONLY create lower hierarchy roles (targetRank > creatorRank)
        if (targetRank <= creatorRank) {
            throw new ApiError(
                HTTP_STATUS.FORBIDDEN,
                `Role '${creator.role}' is not authorized to create a user with role '${userRole}'. You can only create lower hierarchy roles.`
            );
        }
    }

    // Generate 6-digit random password
    const autoPassword = Math.floor(100000 + Math.random() * 900000).toString();

    const newUser = await sequelize.transaction(async (t) => {
        return await User.create({
            fullName,
            email,
            mobile,
            password: autoPassword,
            role: userRole,
            createdById: creatorId,
            parent_id: creatorId
        }, { transaction: t });
    });

    const appUrl = process.env.APP_URL || `${req.protocol}://${req.get('host')}`;

    const promises = [];

    if (mobile) {
        promises.push(sendRegistrationSMS({ mobile, password: autoPassword, url: appUrl }));
    } else {
        promises.push(Promise.resolve({ success: false }));
    }

    if (email) {
        promises.push(
            sendUserCreationEmail({ email, password: autoPassword, url: appUrl })
                .then(() => ({ success: true }))
                .catch((error) => {
                    logger.error("Failed to send welcome email via SMTP:", error);
                    return { success: false, error: error.message || String(error) };
                })
        );
    } else {
        promises.push(Promise.resolve({ success: false, error: "No email provided" }));
    }

    // Run both processes parallelly
    const [smsResult, emailResult] = await Promise.all(promises);

    return res.status(HTTP_STATUS.CREATED).json(
        new ApiResponse(
            HTTP_STATUS.CREATED,
            {
                autoGeneratedPassword: autoPassword,
                smsSent: smsResult ? smsResult.success : false,
                smsError: smsResult && !smsResult.success ? (smsResult.response || smsResult.error) : undefined,
                emailSent: emailResult ? emailResult.success : false,
                emailError: emailResult && !emailResult.success ? emailResult.error : undefined,
                user: newUser
            },
            "Successfully account create SMTP using email and SMS sent"
        )
    );
});

/**
 * @desc    Get list of all users based on hierarchy rank
 * @route   GET /api/entities/all
 * @access  Private
 */
export const getAllUsers = asyncHandler(async (req, res) => {
    const requester = req.user;
    if (!requester) {
        throw new ApiError(HTTP_STATUS.UNAUTHORIZED, "Access Denied. Authentication required.");
    }

    const { page = 1, limit = 10, name, mobile, kyc_status } = req.query;
    const { pageNum, limitNum, offset } = getPaginationParams(page, limit);

    const requesterRank = ROLE_RANK[requester.role];
    const allowedRoles = Object.keys(ROLE_RANK).filter(r => ROLE_RANK[r] > requesterRank);

    // Build conditional where clause
    const whereClause = {
        [Op.and]: [
            {
                [Op.or]: [
                    { id: requester.id },
                    { role: { [Op.in]: allowedRoles } }
                ]
            }
        ]
    };

    if (name) {
        whereClause[Op.and].push({
            fullName: {
                [Op.like]: `%${String(name).trim()}%`
            }
        });
    }

    if (mobile) {
        whereClause[Op.and].push({
            mobile: {
                [Op.like]: `%${String(mobile).trim()}%`
            }
        });
    }

    if (kyc_status) {
        whereClause[Op.and].push({
            pan_verification_status: String(kyc_status).trim()
        });
    }

    const { count, rows: users } = await User.findAndCountAll({
        where: whereClause,
        attributes: { exclude: ['password'] },
        include: [{
            model: User,
            as: 'Creator',
            attributes: ['id', 'fullName', 'email']
        }],
        limit: limitNum,
        offset: offset,
        order: [['createdAt', 'ASC']]
    });

    const responseData = formatPaginatedResponse(count, users, pageNum, limitNum, 'users');

    return res.status(HTTP_STATUS.OK).json(
        new ApiResponse(HTTP_STATUS.OK, responseData, "Users fetched successfully.")
    );
});

/**
 * @desc    Get user details by UUID based on hierarchy
 * @route   GET /api/entities/:uuid
 * @access  Private
 */
export const getUserById = asyncHandler(async (req, res) => {
    const { uuid } = req.params;

    const requester = req.user;
    if (!requester) {
        throw new ApiError(HTTP_STATUS.UNAUTHORIZED, "Access Denied. Authentication required.");
    }

    const user = await User.findOne({
        where: { uuid },
        attributes: { exclude: ['password'] },
        include: [
            {
                model: User,
                as: 'Creator',
                attributes: { exclude: ['password'] },
                required: false
            },
            {
                model: User,
                as: 'CreatedUsers',
                attributes: { exclude: ['password'] },
                required: false
            },
            {
                model: Director,
                as: 'Directors',
                required: false
            },
            {
                model: Product,
                as: 'Products',
                required: false
            },
            {
                model: ProductToken,
                as: 'ProductToken',
                required: false
            },
            {
                model: UserDocument,
                as: 'documents',
                required: false
            },
            {
                model: UserIp,
                as: 'UserIps',
                required: false
            },
            {
                model: Notification,
                as: 'Notifications',
                required: false
            }
        ]
    });

    if (!user) {
        throw new ApiError(HTTP_STATUS.NOT_FOUND, "User not found!");
    }

    const isSelf = requester.id === user.id;
    const requesterRank = ROLE_RANK[requester.role];
    const targetRank = ROLE_RANK[user.role];

    if (!isSelf && targetRank <= requesterRank) {
        throw new ApiError(
            HTTP_STATUS.FORBIDDEN,
            `Role '${requester.role}' is not authorized to view a user with role '${user.role}'. You can only view lower hierarchy users.`
        );
    }

    return res.status(HTTP_STATUS.OK).json(
        new ApiResponse(HTTP_STATUS.OK, user, "User details fetched successfully.")
    );
});

/**
 * @desc    Update user details by UUID based on hierarchy
 * @route   PUT /api/entities/:uuid
 * @access  Private
 */
export const updateUser = asyncHandler(async (req, res) => {
    const { uuid } = req.params;
    const { fullName, email, mobile } = req.body;

    const userToUpdate = await User.findOne({ where: { uuid } });
    if (!userToUpdate) {
        throw new ApiError(HTTP_STATUS.NOT_FOUND, "User not found!");
    }

    const creator = req.user;
    if (!creator) {
        throw new ApiError(HTTP_STATUS.UNAUTHORIZED, "Access Denied. Authentication required.");
    }

    const isSelf = creator.id === userToUpdate.id;
    if (!isSelf) {
        const creatorRank = ROLE_RANK[creator.role];
        const targetUserRank = ROLE_RANK[userToUpdate.role];

        if (targetUserRank <= creatorRank) {
            throw new ApiError(
                HTTP_STATUS.FORBIDDEN,
                `Role '${creator.role}' is not authorized to update a user with role '${userToUpdate.role}'. You can only update lower hierarchy users.`
            );
        }
    }

    await sequelize.transaction(async (t) => {
        await userToUpdate.update({
            fullName: fullName !== undefined ? String(fullName).trim() : userToUpdate.fullName,
            email: email !== undefined ? String(email).trim().toLowerCase() : userToUpdate.email,
            mobile: mobile !== undefined ? String(mobile).trim() : userToUpdate.mobile
        }, { transaction: t });
    });

    return res.status(HTTP_STATUS.OK).json(
        new ApiResponse(HTTP_STATUS.OK, userToUpdate, "User successfully updated!")
    );
});

