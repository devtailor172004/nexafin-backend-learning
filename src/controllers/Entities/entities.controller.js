/**
 * @desc    Get list of users (All users for Admin, or created users for non-Admin)
 * @route   GET /api/entities/created-users
 * @access  Private
 */
export const getCreatedUsers = asyncHandler(async (req, res) => {
    const requester = req.user;
    if (!requester) {
        throw new ApiError(HTTP_STATUS.UNAUTHORIZED, "Access Denied. Authentication required.");
    }

    const { page = 1, limit = 10, search, mobile, role, kyc } = req.query;
    const { pageNum, limitNum, offset } = getPaginationParams(page, limit);

    // Build base where clause: Admin sees all users, others see only users they created
    const whereClause = {};
    if (requester.role !== 'Admin') {
        whereClause.createdById = requester.id;
    }

    const andConditions = [];

    // Optional specific role filter
    if (role) {
        andConditions.push({ role: role });
    }

    // Optional KYC status filter
    if (kyc) {
        andConditions.push({ kyc: String(kyc).trim() });
    }

    if (mobile) {
        andConditions.push({
            mobile: { [Op.like]: `%${String(mobile).trim()}%` }
        });
    }

    // General search filter
    if (search) {
        const searchVal = String(search).trim();
        andConditions.push({
            [Op.or]: [
                { fullName: { [Op.like]: `%${searchVal}%` } },
                { email: { [Op.like]: `%${searchVal}%` } },
                { mobile: { [Op.like]: `%${searchVal}%` } }
            ]
        });
    }

    if (andConditions.length > 0) {
        whereClause[Op.and] = andConditions;
    }

    const { count, rows: users } = await User.findAndCountAll({
        where: whereClause,
        attributes: { exclude: ['password'] },
        limit: limitNum,
        offset: offset,
        order: [['createdAt', 'ASC']]
    });

    const responseData = formatPaginatedResponse(count, users, pageNum, limitNum, 'users');

    return res.status(HTTP_STATUS.OK).json(
        new ApiResponse(HTTP_STATUS.OK, responseData, "Created users fetched successfully.")
    );
});

